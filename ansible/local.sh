#!/usr/bin/env bash
set -euo pipefail
export LIBVIRT_DEFAULT_URI=qemu:///system
cd "$(dirname "$0")"

NAME=home-dev
DIR=/var/lib/libvirt/images
BASE=$DIR/debian-13-genericcloud-amd64.qcow2

# Remove the previous VM and its disks (the base image is kept)

virsh destroy "$NAME" 2>/dev/null || true
virsh undefine "$NAME" --remove-all-storage --nvram 2>/dev/null || true

# Thin OS disk on top of the base image

sudo qemu-img create -f qcow2 -b "$BASE" -F qcow2 "$DIR/$NAME.qcow2" 20G

# --boot uefi: under the default legacy BIOS, Debian 13's kernel reboot-loops right after GRUB

virt-install --name "$NAME" --memory 4096 --vcpus 2 --import \
  --disk path="$DIR/$NAME.qcow2" \
  --os-variant debian12 --network network=default --graphics none --boot uefi \
  --cloud-init user-data=vm/user-data.yaml --noautoconsole

# Wait for the VM to get a DHCP lease, then point the inventory at it

echo "Waiting for $NAME to get an IP..."
IP=
until [ -n "$IP" ]; do
  sleep 2
  IP=$(virsh domifaddr "$NAME" 2>/dev/null | awk '$3 == "ipv4" { sub(/\/.*/, "", $4); print $4; exit }' || true)
done
echo "$NAME is at $IP"

cat > inventory.ini <<EOF
# Generated by local.sh
[server]
$NAME ansible_host=$IP ansible_user=cube
EOF
